#!/usr/bin/env python3
"""Embed the admin console's static files into a C source file.

Keeping the assets as real files means they stay editable and lintable, while
the appliance binary carries them so there is nothing to install alongside it.
"""
import sys, os

ASSETS = [
    ("WEBUI_INDEX_HTML", "index.html"),
    ("WEBUI_VLAN_JS",    "vlan.js"),
    ("WEBUI_STYLE_CSS",  "style.css"),
]

def c_escape(data: bytes) -> str:
    out = []
    for b in data:
        ch = chr(b)
        if   ch == '\\': out.append('\\\\')
        elif ch == '"':  out.append('\\"')
        elif ch == '\n': out.append('\\n"\n"')
        elif ch == '\r': out.append('\\r')
        elif ch == '\t': out.append('\\t')
        elif 32 <= b < 127: out.append(ch)
        else: out.append('\\%03o' % b)
    return ''.join(out)

def main():
    srcdir, outfile = sys.argv[1], sys.argv[2]
    parts = ['/* Generated by tools/embed_assets.py - do not edit.\n'
             ' * Source: src/webui/static/ */\n\n']
    for sym, name in ASSETS:
        path = os.path.join(srcdir, name)
        with open(path, 'rb') as f:
            data = f.read()
        parts.append('const char %s[] =\n"%s";\n\n' % (sym, c_escape(data)))
    with open(outfile, 'w') as f:
        f.write(''.join(parts))
    print("embedded %d assets -> %s" % (len(ASSETS), outfile))

if __name__ == '__main__':
    main()
