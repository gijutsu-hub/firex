const char *ha_state_name(ha_state_t s) {
    switch (s) {
        case HA_STATE_MASTER: return "MASTER";
        case HA_STATE_BACKUP: return "BACKUP";
        case HA_STATE_FAULT:  return "FAULT";
        default:              return "UNKNOWN";
    }
}

ha_state_t ha_state_from(const char *s) {
    if (!s) return HA_STATE_UNKNOWN;
    if (!strncasecmp(s, "MASTER", 6)) return HA_STATE_MASTER;
    if (!strncasecmp(s, "BACKUP", 6)) return HA_STATE_BACKUP;
    if (!strncasecmp(s, "FAULT", 5))  return HA_STATE_FAULT;
    return HA_STATE_UNKNOWN;
}

const char *ha_role_name(ha_role_t r) {
    return r == HA_ROLE_SECONDARY ? "secondary" : "primary";
}

ha_role_t ha_role_from(const char *s) {
    if (s && (!strcasecmp(s, "secondary") || !strcasecmp(s, "backup")))
        return HA_ROLE_SECONDARY;
    return HA_ROLE_PRIMARY;
}

int ha_init(ha_ctx_t *h, const ha_cfg_t *cfg) {
    memset(h, 0, sizeof(*h));
    pthread_mutex_init(&h->lock, NULL);
    if (cfg) h->cfg = *cfg;

    if (!h->cfg.vrrp_id)          h->cfg.vrrp_id = HA_DEFAULT_VRID;
    if (!h->cfg.advert_interval)  h->cfg.advert_interval = 1;
    if (!h->cfg.conntrack_port)   h->cfg.conntrack_port = HA_DEFAULT_CT_PORT;
    if (!h->cfg.config_sync_port) h->cfg.config_sync_port = HA_DEFAULT_SYNC_PORT;
    if (!h->cfg.priority)
        h->cfg.priority = (h->cfg.role == HA_ROLE_PRIMARY) ? 150 : 100;

    h->state = HA_STATE_UNKNOWN;
    return 0;
}

void ha_shutdown(ha_ctx_t *h) {
    if (!h) return;
    explicit_bzero(h->cfg.sync_secret, sizeof(h->cfg.sync_secret));
    explicit_bzero(h->cfg.vrrp_password, sizeof(h->cfg.vrrp_password));
    pthread_mutex_destroy(&h->lock);
}

/* ═══════════════════ state ═══════════════════ */

void ha_set_state(ha_ctx_t *h, ha_state_t s) {
    pthread_mutex_lock(&h->lock);
    if (s != h->state) {
        printf("[%s] HA: %s -> %s\n", BRAND_PRODUCT,
               ha_state_name(h->state), ha_state_name(s));
        h->state = s;
        h->state_since = time(NULL);
        h->transitions++;
    }
    pthread_mutex_unlock(&h->lock);
}

ha_state_t ha_read_state(ha_ctx_t *h) {
    FILE *f = fopen(HA_STATE_FILE, "r");
    if (!f) return h->state;

    char buf[32] = "";
    if (!fgets(buf, sizeof(buf), f)) { fclose(f); return h->state; }
    fclose(f);

    ha_state_t s = ha_state_from(buf);
    if (s != HA_STATE_UNKNOWN) ha_set_state(h, s);
    return h->state;
}

/* ═══════════════════ generated configuration ═══════════════════ */

/* Files that carry a shared secret are 0600 from the moment they exist. */
static FILE *open_private(const char *path) {
    int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    if (fd < 0) return NULL;
    FILE *f = fdopen(fd, "w");
    if (!f) { close(fd); return NULL; }
    return f;
}

int ha_generate_notify(ha_ctx_t *h, const char *path) {
    (void)h;
    FILE *f = open_private(path);
    if (!f) return -1;

    /*
     * keepalived passes the new state as $3. Writing it to a file rather
     * than calling back into the console keeps this script dependency-free
     * and means a transition is recorded even if the daemon is restarting.
     */
    fprintf(f,
        "#!/bin/sh\n"
        "# Generated by %s %s -- do not edit by hand.\n"
        "# Called by keepalived on every VRRP transition: $1=type $2=name $3=state\n"
        "set -e\n"
        "mkdir -p \"$(dirname %s)\"\n"
        "printf '%%s\\n' \"$3\" > %s\n"
        "logger -t %s \"VRRP state -> $3\" 2>/dev/null || true\n",
        BRAND_PRODUCT, BRAND_VERSION, HA_STATE_FILE, HA_STATE_FILE,
        BRAND_DAEMON);

    fflush(f);
    if (fsync(fileno(f)) != 0)
        fprintf(stderr, "[%s] %s: fsync failed\n", BRAND_PRODUCT, path);
    fclose(f);

    if (chmod(path, 0700) != 0)
        fprintf(stderr, "[%s] could not make %s executable\n",
                BRAND_PRODUCT, path);
    return 0;
}

int ha_generate_keepalived(ha_ctx_t *h, vlan_ctx_t *v, const char *path,
                           const char *notify_script) {
    if (!h->cfg.enabled) return 0;

    FILE *f = open_private(path);
    if (!f) {
        snprintf(h->last_error, sizeof(h->last_error),
                 "cannot write %s (%s)", path, strerror(errno));
        return -1;
    }

    fprintf(f, "# %s %s - generated, do not edit by hand\n", BRAND_PRODUCT,
            BRAND_VERSION);
    fprintf(f, "# This node is the %s, priority %d.\n\n",
            ha_role_name(h->cfg.role), h->cfg.priority);

    fprintf(f, "global_defs {\n");
    fprintf(f, "    router_id %s-%s\n", BRAND_PRODUCT, ha_role_name(h->cfg.role));
    fprintf(f, "    enable_script_security\n");
    fprintf(f, "    script_user root\n");
    fprintf(f, "}\n\n");

    fprintf(f, "vrrp_instance FIREX_VI {\n");
    /*
     * Both nodes start as BACKUP and let priority decide. Declaring the
     * primary MASTER makes it claim the address before it has heard from the
     * peer, which is how you get two masters during a restart.
     */
    fprintf(f, "    state BACKUP\n");
    fprintf(f, "    interface %s\n", h->cfg.sync_interface);
    fprintf(f, "    virtual_router_id %d\n", h->cfg.vrrp_id);
    fprintf(f, "    priority %d\n", h->cfg.priority);
    fprintf(f, "    advert_int %d\n", h->cfg.advert_interval);
    fprintf(f, "    %s\n", h->cfg.preempt ? "preempt" : "nopreempt");

    if (h->cfg.sync_address[0])
        fprintf(f, "    unicast_src_ip %s\n", h->cfg.sync_address);
    if (h->cfg.peer_address[0]) {
        /* Unicast rather than multicast: it crosses switches that filter
         * 224.0.0.18 and makes the peering explicit. */
        fprintf(f, "    unicast_peer {\n        %s\n    }\n",
                h->cfg.peer_address);
    }

    if (h->cfg.vrrp_password[0]) {
        fprintf(f, "    authentication {\n");
        fprintf(f, "        auth_type PASS\n");
        /* VRRPv2 only uses the first 8 characters; say so rather than let a
         * longer password look stronger than it is. */
        fprintf(f, "        auth_pass %.8s\n", h->cfg.vrrp_password);
        fprintf(f, "    }\n");
    }

    int vips = 0;
    fprintf(f, "    virtual_ipaddress {\n");
    char abuf[INET_ADDRSTRLEN];
    for (int i = 0; i < v->vlan_count; i++) {
        vlan_config_t *c = &v->vlans[i];
        if (!c->enabled || !c->gateway || !c->netmask) continue;

        /* The interface the VLAN lives on, so keepalived puts the address in
         * the right place. */
        char dev[IFNAME_LEN * 2] = "";
        for (int p = 0; p < v->port_count; p++) {
            port_config_t *pt = &v->ports[p];
            if (!fx_ifname_safe(pt->ifname, IFNAME_LEN)) continue;
            if ((pt->mode == PORT_MODE_TRUNK || pt->mode == PORT_MODE_HYBRID) &&
                port_vlan_permitted(pt, c->vlan_id)) {
                snprintf(dev, sizeof(dev), "%s.%u", pt->ifname, c->vlan_id);
                break;
            }
            if (pt->mode == PORT_MODE_ACCESS && pt->pvid == c->vlan_id) {
                snprintf(dev, sizeof(dev), "%s", pt->ifname);
                break;
            }
        }
        if (!dev[0]) continue;

        fprintf(f, "        %s/%d dev %s label %s:fx\n",
                fx_ip_str(c->gateway, abuf, sizeof(abuf)),
                fx_netmask_to_cidr(c->netmask), dev, dev);
        vips++;
    }
    fprintf(f, "    }\n");

    if (notify_script && *notify_script) {
        fprintf(f, "    notify_master \"%s INSTANCE FIREX_VI MASTER\"\n",
                notify_script);
        fprintf(f, "    notify_backup \"%s INSTANCE FIREX_VI BACKUP\"\n",
                notify_script);
        fprintf(f, "    notify_fault  \"%s INSTANCE FIREX_VI FAULT\"\n",
                notify_script);
    }
    fprintf(f, "}\n");

    fflush(f);
    if (fsync(fileno(f)) != 0)
        fprintf(stderr, "[%s] %s: fsync failed\n", BRAND_PRODUCT, path);
    fclose(f);

    pthread_mutex_lock(&h->lock);
    h->vips = vips;
    pthread_mutex_unlock(&h->lock);
    return vips;
}

int ha_generate_conntrackd(ha_ctx_t *h, const char *path) {
    if (!h->cfg.enabled || !h->cfg.conntrack_sync) return 0;

    FILE *f = open_private(path);
    if (!f) {
        snprintf(h->last_error, sizeof(h->last_error),
                 "cannot write %s (%s)", path, strerror(errno));
        return -1;
    }

    fprintf(f, "# %s %s - generated, do not edit by hand\n\n",
            BRAND_PRODUCT, BRAND_VERSION);

    fprintf(f, "Sync {\n");
    /*
     * FTFW resends what the peer missed rather than hoping, which is what
     * makes a failover keep established connections instead of merely
     * knowing about recent ones.
     */
    fprintf(f, "    Mode FTFW {\n");
    fprintf(f, "        DisableExternalCache Off\n");
    fprintf(f, "    }\n");
    fprintf(f, "    UDP {\n");
    fprintf(f, "        IPv4_address %s\n", h->cfg.sync_address);
    fprintf(f, "        IPv4_Destination_Address %s\n", h->cfg.peer_address);
    fprintf(f, "        Port %d\n", h->cfg.conntrack_port);
    fprintf(f, "        Interface %s\n", h->cfg.sync_interface);
    fprintf(f, "        SndSocketBuffer 1249280\n");
    fprintf(f, "        RcvSocketBuffer 1249280\n");
    fprintf(f, "        Checksum on\n");
    fprintf(f, "    }\n");
    fprintf(f, "}\n\n");

    fprintf(f, "General {\n");
    fprintf(f, "    Systemd off\n");
    fprintf(f, "    HashSize 32768\n");
    fprintf(f, "    HashLimit 131072\n");
    fprintf(f, "    LogFile off\n");
    fprintf(f, "    Syslog on\n");
    fprintf(f, "    LockFile /var/lock/conntrackd.lock\n");
    fprintf(f, "    UNIX {\n        Path /var/run/conntrackd.ctl\n");
    fprintf(f, "        Backlog 20\n    }\n");
    fprintf(f, "    NetlinkBufferSize 2097152\n");
    fprintf(f, "    NetlinkBufferSizeMaxGrowth 8388608\n");
    fprintf(f, "    Filter From Userspace {\n");
    fprintf(f, "        Protocol Accept {\n            TCP\n            UDP\n"
               "            SCTP\n        }\n");
    /*
     * Loopback and the sync link itself are excluded: replicating them is
     * pointless and the sync traffic would feed on itself.
     */
    fprintf(f, "        Address Ignore {\n");
    fprintf(f, "            IPv4_address 127.0.0.1\n");
    if (h->cfg.sync_address[0])
        fprintf(f, "            IPv4_address %s\n", h->cfg.sync_address);
    if (h->cfg.peer_address[0])
        fprintf(f, "            IPv4_address %s\n", h->cfg.peer_address);
    fprintf(f, "        }\n    }\n");
    fprintf(f, "}\n");

    fflush(f);
    if (fsync(fileno(f)) != 0)
        fprintf(stderr, "[%s] %s: fsync failed\n", BRAND_PRODUCT, path);
    fclose(f);
    return 0;
}

/* ═══════════════════ signing ═══════════════════ */

static bool ct_eq(const char *a, const char *b) {
    size_t la = strlen(a), lb = strlen(b);
    unsigned char d = (unsigned char)(la ^ lb);
    size_t n = la < lb ? la : lb;
    for (size_t i = 0; i < n; i++) d |= (unsigned char)(a[i] ^ b[i]);
    return d == 0 && la == lb;
}

int ha_sign(const char *secret, time_t ts, const void *body, size_t len,
            char *out, size_t outlen) {
    if (!secret || !*secret || !out || outlen < HA_SIG_LEN) return -1;
    if (len && !body) return -1;

    /*
     * The timestamp is inside the signed material, not merely sent beside
     * it: otherwise a captured push could be replayed with a fresh header.
     */
    char prefix[32];
    int pl = snprintf(prefix, sizeof(prefix), "%lld\n", (long long)ts);
    if (pl <= 0) return -1;

    unsigned char mac[EVP_MAX_MD_SIZE];
    unsigned int maclen = 0;

    HMAC_CTX *c = HMAC_CTX_new();
    if (!c) return -1;
    if (HMAC_Init_ex(c, secret, (int)strlen(secret), EVP_sha256(), NULL) != 1 ||
        HMAC_Update(c, (const unsigned char *)prefix, (size_t)pl) != 1 ||
        (len && HMAC_Update(c, body, len) != 1) ||
        HMAC_Final(c, mac, &maclen) != 1) {
        HMAC_CTX_free(c);
        return -1;
    }
    HMAC_CTX_free(c);

    if (maclen * 2 + 1 > outlen) return -1;
    static const char HEX[] = "0123456789abcdef";
    for (unsigned i = 0; i < maclen; i++) {
        out[i * 2]     = HEX[mac[i] >> 4];
        out[i * 2 + 1] = HEX[mac[i] & 0x0f];
    }
    out[maclen * 2] = '\0';
    return (int)(maclen * 2);
}

bool ha_verify(const char *secret, const char *ts_header, const char *sig_header,
               const void *body, size_t len, time_t now,
               char *why, size_t whylen) {
    if (why && whylen) why[0] = '\0';

    if (!secret || !*secret) {
        if (why) snprintf(why, whylen, "no sync secret is configured");
        return false;
    }
    if (!ts_header || !*ts_header || !sig_header || !*sig_header) {
        if (why) snprintf(why, whylen, "the request is not signed");
        return false;
    }

    char *end = NULL;
    long long ts = strtoll(ts_header, &end, 10);
    if (end == ts_header || ts <= 0) {
        if (why) snprintf(why, whylen, "the timestamp is not a number");
        return false;
    }

    long long drift = (long long)now - ts;
    if (drift < 0) drift = -drift;
    if (drift > HA_REPLAY_WINDOW) {
        if (why)
            snprintf(why, whylen,
                     "the timestamp is %llds away from now, outside the %d "
                     "second window; check the clocks on both nodes",
                     drift, HA_REPLAY_WINDOW);
        return false;
    }

    char want[HA_SIG_LEN];
    if (ha_sign(secret, (time_t)ts, body, len, want, sizeof(want)) < 0) {
        if (why) snprintf(why, whylen, "could not compute the signature");
        return false;
    }

    if (!ct_eq(want, sig_header)) {
        if (why)
            snprintf(why, whylen,
                     "the signature does not match; the peers' sync secrets "
                     "differ, or the body was altered in transit");
        return false;
    }
    return true;
}

/* ═══════════════════ replication ═══════════════════ */

int ha_push_config(ha_ctx_t *h, const char *config_path,
                   char *why, size_t whylen) {
    if (why && whylen) why[0] = '\0';

    if (!h->cfg.enabled || !h->cfg.config_sync) return 0;
    if (h->cfg.role != HA_ROLE_PRIMARY) {
        if (why) snprintf(why, whylen,
                          "only the primary pushes configuration");
        return -1;
    }
    if (!h->cfg.peer_address[0] || !h->cfg.sync_secret[0]) {
        if (why) snprintf(why, whylen,
                          "no peer address or sync secret is configured");
        return -1;
    }

    /*
     * Pushing is this node opening a session to the peer, so the gap
     * applies. RECEIVING one does not and is not gated: /api/ha/sync is
     * inbound, already authenticated by signature, and a diode pointing in
     * is meant to let exactly that through.
     */
    if (!egress_permitted(EGRESS_HA, why, whylen)) {
        if (why && whylen && !why[0])
            snprintf(why, whylen, "the air gap is shut; the peer was not contacted");
        return -1;
    }

    FILE *f = fopen(config_path, "rb");
    if (!f) {
        if (why) snprintf(why, whylen, "cannot read %s", config_path);
        return -1;
    }
    size_t cap = 512 * 1024;
    char *body = malloc(cap);
    if (!body) { fclose(f); if (why) snprintf(why, whylen, "out of memory"); return -1; }
    size_t blen = fread(body, 1, cap, f);
    fclose(f);
    if (!blen) {
        free(body);
        if (why) snprintf(why, whylen, "the configuration file is empty");
        return -1;
    }

    time_t ts = time(NULL);
    char sig[HA_SIG_LEN];
    if (ha_sign(h->cfg.sync_secret, ts, body, blen, sig, sizeof(sig)) < 0) {
        free(body);
        if (why) snprintf(why, whylen, "could not sign the push");
        return -1;
    }

    char portstr[8];
    snprintf(portstr, sizeof(portstr), "%d", h->cfg.config_sync_port);

    struct addrinfo hints, *res = NULL;
    memset(&hints, 0, sizeof(hints));
    hints.ai_family   = AF_INET;
    hints.ai_socktype = SOCK_STREAM;
    if (getaddrinfo(h->cfg.peer_address, portstr, &hints, &res) != 0 || !res) {
        free(body);
        if (why) snprintf(why, whylen, "cannot resolve the peer");
        return -1;
    }

    int fd = socket(res->ai_family, SOCK_STREAM, 0);
    if (fd < 0) {
        freeaddrinfo(res); free(body);
        if (why) snprintf(why, whylen, "no socket for the push");
        return -1;
    }
    struct timeval tv = { 5, 0 };
    setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
    setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));

    if (connect(fd, res->ai_addr, res->ai_addrlen) != 0) {
        close(fd); freeaddrinfo(res); free(body);
        if (why) snprintf(why, whylen, "the peer did not accept a connection (%s)",
                          strerror(errno));
        return -1;
    }
    freeaddrinfo(res);

    char hdr[512];
    int hl = snprintf(hdr, sizeof(hdr),
        "POST /api/ha/sync HTTP/1.1\r\n"
        "Host: %s:%d\r\n"
        "Content-Type: text/plain\r\n"
        "Content-Length: %zu\r\n"
        "X-FireX-HA-Timestamp: %lld\r\n"
        "X-FireX-HA-Signature: %s\r\n"
        "Connection: close\r\n\r\n",
        h->cfg.peer_address, h->cfg.config_sync_port, blen,
        (long long)ts, sig);

    bool sent = hl > 0 && write(fd, hdr, (size_t)hl) == hl &&
                write(fd, body, blen) == (ssize_t)blen;
    free(body);

    if (!sent) {
        close(fd);
        if (why) snprintf(why, whylen, "the push could not be written");
        return -1;
    }

    char resp[512] = "";
    ssize_t n = read(fd, resp, sizeof(resp) - 1);
    close(fd);

    if (n <= 0) {
        if (why) snprintf(why, whylen, "the peer closed without replying");
        return -1;
    }
    resp[n] = '\0';

    if (!strstr(resp, "200 OK")) {
        char *nl = strpbrk(resp, "\r\n");
        if (nl) *nl = '\0';
        if (why) snprintf(why, whylen, "the peer refused the push: %s", resp);
        pthread_mutex_lock(&h->lock);
        h->pushes_rejected++;
        pthread_mutex_unlock(&h->lock);
        return -1;
    }

    pthread_mutex_lock(&h->lock);
    h->pushes_sent++;
    pthread_mutex_unlock(&h->lock);

    printf("[%s] HA: configuration pushed to %s\n",
           BRAND_PRODUCT, h->cfg.peer_address);
    return 0;
}

/* ═══════════════════ provisioning ═══════════════════ */

int ha_apply(ha_ctx_t *h, vlan_ctx_t *v) {
    if (!h->cfg.enabled) return 0;

    printf("[%s] HA: %s, VRID %d, priority %d, peer %s\n", BRAND_PRODUCT,
           ha_role_name(h->cfg.role), h->cfg.vrrp_id, h->cfg.priority,
           h->cfg.peer_address[0] ? h->cfg.peer_address : "(none)");

    if (mkdir("/etc/keepalived", 0750) != 0 && errno != EEXIST)
        fprintf(stderr, "[%s] cannot create /etc/keepalived (%s)\n",
                BRAND_PRODUCT, strerror(errno));

    const char *notify = BRAND_CONFIG_DIR "/ha-notify.sh";
    if (ha_generate_notify(h, notify) != 0)
        fprintf(stderr, "[%s] could not write %s\n", BRAND_PRODUCT, notify);

    int vips = ha_generate_keepalived(h, v, "/etc/keepalived/keepalived.conf",
                                      notify);
    if (vips < 0) return -1;
    printf("  [HA] %d virtual address(es) under VRRP\n", vips);

    if (h->cfg.conntrack_sync) {
        if (ha_generate_conntrackd(h, "/etc/conntrackd/conntrackd.conf") == 0)
            printf("  [HA] connection sync to %s:%d over %s\n",
                   h->cfg.peer_address, h->cfg.conntrack_port,
                   h->cfg.sync_interface);
    }

    /* VRRP and the sync protocols have to reach this box. */
    char cmd[256];
    fx_run("iptables -I INPUT -p vrrp -j ACCEPT");
    fx_try("iptables -I INPUT -p 112 -j ACCEPT 2>/dev/null");
    if (h->cfg.conntrack_sync && h->cfg.peer_address[0]) {
        snprintf(cmd, sizeof(cmd),
                 "iptables -I INPUT -s %s -p udp --dport %d -j ACCEPT",
                 h->cfg.peer_address, h->cfg.conntrack_port);
        fx_run(cmd);
    }

    fx_try("systemctl restart keepalived 2>/dev/null");
    if (h->cfg.conntrack_sync)
        fx_try("systemctl restart conntrackd 2>/dev/null");

    pthread_mutex_lock(&h->lock);
    h->applied = true;
    pthread_mutex_unlock(&h->lock);
    return vips;
}

int ha_teardown(ha_ctx_t *h) {
    if (!h->cfg.enabled) return 0;

    char cmd[256];
    fx_try("systemctl stop keepalived 2>/dev/null");
    fx_try("systemctl stop conntrackd 2>/dev/null");
    fx_try("iptables -D INPUT -p vrrp -j ACCEPT 2>/dev/null");
    fx_try("iptables -D INPUT -p 112 -j ACCEPT 2>/dev/null");
    if (h->cfg.conntrack_sync && h->cfg.peer_address[0]) {
        snprintf(cmd, sizeof(cmd),
                 "iptables -D INPUT -s %s -p udp --dport %d -j ACCEPT 2>/dev/null",
                 h->cfg.peer_address, h->cfg.conntrack_port);
        fx_try(cmd);
    }

    pthread_mutex_lock(&h->lock);
    h->applied = false;
    pthread_mutex_unlock(&h->lock);
    return 0;
}
